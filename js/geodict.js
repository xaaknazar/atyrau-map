/**
 * Попытаться найти координаты в локальном справочнике.
 *
 * Стратегия поиска (от точного к общему):
 * 1. Улица + Дом → если есть в словаре
 * 2. Улица → известные улицы
 * 3. Город / Населённый пункт → микрорайоны и посёлки
 * 4. Район → fallback по району
 *
 * @param {Object} crime — объект инцидента с полями city, street, house, district
 * @returns {{lat: number, lng: number} | null}
 */
function lookupLocalGeo(crime) {
    var city = (crime.city || "").toUpperCase().trim();
    var street = (crime.street || "").replace(/№/g, "").toUpperCase().trim();
    var district = (crime.district || "").toUpperCase().trim();

    // 1. Улица — если это известная улица
    if (street && ATYRAU_GEODICT[street]) {
        return ATYRAU_GEODICT[street];
    }

    // 2. Город / микрорайон / населённый пункт
    if (city && ATYRAU_GEODICT[city]) {
        return ATYRAU_GEODICT[city];
    }

    // 3. Район (fallback)
    if (district && ATYRAU_GEODICT[district]) {
        return ATYRAU_GEODICT[district];
    }

    // 4. Попробуем комбинации с районом
    var districtKey = district + " АУДАНЫ";
    if (ATYRAU_GEODICT[districtKey]) {
        return ATYRAU_GEODICT[districtKey];
    }

    return null;
}
