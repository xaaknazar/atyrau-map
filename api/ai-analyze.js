// Vercel serverless function — прокси к OpenAI.
// Ключ хранится в переменной окружения OPENAI_API_KEY (Vercel → Settings → Environment Variables)
// и НИКОГДА не попадает в клиентский код.
module.exports = async function handler(req, res) {
    if (req.method !== "POST") {
        res.status(405).json({ error: "Method not allowed" });
        return;
    }

    var apiKey = process.env.OPENAI_API_KEY;
    if (!apiKey) {
        res.status(500).json({ error: "Сервер не настроен: добавьте переменную окружения OPENAI_API_KEY в настройках Vercel." });
        return;
    }

    try {
        var body = req.body;
        if (typeof body === "string") { try { body = JSON.parse(body); } catch (e) { body = {}; } }
        body = body || {};
        var summary = (body.summary || "").toString();
        if (!summary.trim()) {
            res.status(400).json({ error: "Нет данных для анализа." });
            return;
        }

        var isKz = (body.lang === "kz");

        var systemPrompt = isKz ? [
            "Сен — Атырау қаласы прокуратурасының аға талдаушысысың.",
            "Міндетің: ЕРДР статистикасы бойынша қылмыстық ахуалдың АҒЫМДАҒЫ проблемаларын анықтап, прокурор дереу назар аударуы тиіс мәселелерді көрсету.",
            "ҚАТАҢ ЕРЕЖЕЛЕР:",
            "1. Тек БЕРІЛГЕН ДЕРЕКТЕРДЕГІ фактілер мен сандар. Сан, бап, көше, пайызды ойдан шығаруға болмайды. Дерек болмаса — «дерек жоқ» деп жаз.",
            "2. Әр тұжырымды нақты санмен немесе үлеспен раста, мысалы: «188-бап — 142 жағдай (барлығының 27%-ы)».",
            "3. Қысқа әрі нақты жаз, артық сөзсіз.",
            "4. Аномалияларға, шоғырлануға және тәуекелге назар аудар.",
            "4.1. БАРЛЫҚ деректер Атырау қаласына қатысты, сондықтан «Атырау қаласында/ауданында қылмыс шоғырланған» деген тұжырым жазба — бұл өзінен-өзі түсінікті. Шоғырлануды тек қала ішіндегі нақты аудан, шағынаудан, көше немесе аймақ бойынша көрсет.",
            "5. Тіл — қазақ тілі.",
            "6. Формат — ТЕК Markdown: ## және ### тақырыптар, **қалың** (сандар үшін), «- » тізімдер, --- бөлгіш. Кесте мен HTML тегтерін қолданба."
        ].join("\n") : [
            "Ты — старший аналитик прокуратуры города Атырау (Казахстан).",
            "Задача: по статистике ЕРДР выявить ТЕКУЩИЕ проблемы криминогенной обстановки, на которые прокурору нужно обратить внимание прямо сейчас.",
            "ЖЕЛЕЗНЫЕ ПРАВИЛА:",
            "1. Только факты и цифры ИЗ ПРЕДОСТАВЛЕННЫХ ДАННЫХ. Запрещено выдумывать числа, статьи, улицы, проценты. Если данных по пункту нет — честно напиши «нет данных».",
            "2. Каждый вывод подкрепляй конкретной цифрой или долей, например: «ст. 188 — 142 случая (27% от всех)».",
            "3. Пиши кратко и по делу, как для занятого руководителя. Без воды, без общих рассуждений «в целом».",
            "4. Делай акцент на аномалиях, концентрациях и рисках — на том, что требует реакции надзора.",
            "4.1. ВСЕ данные относятся к г. Атырау, поэтому НЕ пиши выводов вида «концентрация преступлений в районе/городе Атырау» — это очевидно. Концентрацию указывай только по конкретным районам, микрорайонам, улицам или зонам внутри города.",
            "5. Язык — русский.",
            "6. Формат — ТОЛЬКО Markdown из набора: заголовки ## и ###, **жирный** (для чисел и ключевых выводов), маркированные списки через «- », разделитель ---. НЕ используй таблицы и HTML-теги."
        ].join("\n");

        var userPrompt = isKz ? [
            "Төмендегі құрылым бойынша қысқа аналитикалық есеп дайында. Әр бөлімде деректерден алынған нақты сандар болсын, артық сөзсіз.",
            "",
            "## Ең басты — назар аудару керек",
            "Дәл қазір ең өткір 3–5 мәселе, әрқайсысы санмен. Бұл — прокурорға арналған түйін.",
            "",
            "## Қылмыс ошақтары",
            "Шоғырлану бойынша топ-5 аймақ/аудан/көше: атауы (аудан/көше), қылмыс саны, негізгі бап, шың уақыты. Аймақтың несімен қауіпті екенін сандармен көрсет.",
            "",
            "## Қауіпті уақыт",
            "Ең қауіпті сағаттар мен апта күндері — сандармен.",
            "",
            "## Қылмыс түрлері",
            "ҚК-нің топ баптары сандармен және үлестермен. Әр бапты қысқаша түсіндір. Мүмкін болса орын/уақытпен байланыстыр.",
            "",
            "## Күдіктілер мен осал топтар",
            "Жас топтары, кәмелетке толмағандар үлесі, жыныс, кәсібі, білімі — айқын ауытқулар бар жерде (сандармен).",
            "",
            "## Инфрақұрылым олқылықтары",
            "Камера, соқыр аймақ (камерасыз), жарықсыз көше, қараусыз ғимарат санын қылмыс ошақтарымен салыстыр. Бақылау мен жарық жетіспейтін жерлерді көрсет.",
            "",
            "## Прокурордың басым әрекеттері (ТОП-5)",
            "Нақты, мекенжайлы шаралар: қай жерде патруль/камера/жарықты күшейту, қандай қадағалау әрекеттері, қай аймақ пен уақыт бойынша. Әр тармақ деректегі санға байланысты.",
            "",
            "---",
            "ТАЛДАУ ҮШІН ДЕРЕКТЕР:",
            summary
        ].join("\n") : [
            "Подготовь сжатый аналитический отчёт строго по структуре ниже. В каждом разделе — конкретные цифры из данных, без воды.",
            "",
            "## Главное — на что обратить внимание",
            "3–5 самых острых проблем прямо сейчас, каждая с цифрой. Это выжимка для прокурора.",
            "",
            "## Очаги преступности",
            "Топ-5 зон/районов/улиц по концентрации: название (район/улица), число преступлений, основная статья, пиковое время. Чем именно зона опасна — по цифрам.",
            "",
            "## Время риска",
            "Самые опасные часы суток и дни недели — с числами. Когда концентрируется преступность.",
            "",
            "## Виды преступлений",
            "Топ статей УК РК с числами и долями. Коротко расшифруй каждую статью. Свяжи с местом/временем, где это видно из данных.",
            "",
            "## Подозреваемые и уязвимые группы",
            "Возрастные группы, доля несовершеннолетних, пол, род занятий, образование — где есть выраженные перекосы (с цифрами).",
            "",
            "## Пробелы инфраструктуры",
            "Сопоставь число камер, слепых зон (без камер), неосвещённых улиц и заброшенных зданий с очагами преступности. Где не хватает наблюдения и освещения.",
            "",
            "## Приоритетные действия прокурора (ТОП-5)",
            "Конкретные адресные меры: где усилить патрулирование/камеры/освещение, какие надзорные действия и по каким зонам/времени. Каждый пункт привязан к цифре из данных.",
            "",
            "---",
            "ДАННЫЕ ДЛЯ АНАЛИЗА:",
            summary
        ].join("\n");

        var aiResp = await fetch("https://api.openai.com/v1/chat/completions", {
            method: "POST",
            headers: {
                "Content-Type": "application/json",
                "Authorization": "Bearer " + apiKey
            },
            body: JSON.stringify({
                model: "gpt-4o",
                max_tokens: 3500,
                temperature: 0.2,
                messages: [
                    { role: "system", content: systemPrompt },
                    { role: "user", content: userPrompt }
                ]
            })
        });

        if (!aiResp.ok) {
            var errText = await aiResp.text();
            res.status(502).json({ error: "OpenAI API " + aiResp.status + ": " + errText.slice(0, 600) });
            return;
        }

        var data = await aiResp.json();
        var text = data && data.choices && data.choices[0] && data.choices[0].message
            ? data.choices[0].message.content
            : "";
        if (!text) { res.status(502).json({ error: "Пустой ответ от модели." }); return; }

        res.status(200).json({ text: text });
    } catch (e) {
        res.status(500).json({ error: (e && e.message) ? e.message : "Внутренняя ошибка функции." });
    }
};
